#!/usr/bin/env node

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Unicode's own list of characters that look alike (UTS #39, "Unicode Security Mechanisms").
const CONFUSABLES_URL = 'https://www.unicode.org/Public/security/latest/confusables.txt';

const OUTPUT_FILE = join(
	process.cwd(),
	'src',
	'frontend',
	'src',
	'lib',
	'constants',
	'confusables.constants.ts'
);

// Token symbols and names are compared in plain Latin letters and digits, so only the characters
// that look like those are kept.
const LATIN_LETTERS_AND_DIGITS = /^[A-Za-z0-9]+$/;

const fromCodePoints = (hex: string): string =>
	String.fromCodePoint(
		...hex
			.trim()
			.split(/\s+/)
			.map((codePoint) => parseInt(codePoint, 16))
	);

const escape = (text: string): string =>
	[...text]
		.map((char) =>
			/^[A-Za-z0-9]$/.test(char)
				? char
				: `\\u{${(char.codePointAt(0) ?? 0).toString(16).toUpperCase()}}`
		)
		.join('');

const buildConfusables = async (): Promise<[string, string][]> => {
	const response = await fetch(CONFUSABLES_URL);

	if (!response.ok) {
		throw new Error(`Could not download ${CONFUSABLES_URL}: ${response.status}`);
	}

	const lines = (await response.text()).split('\n');

	return lines.reduce<[string, string][]>((acc, line) => {
		const [data] = line.split('#');
		const [sourceHex, targetHex] = data.split(';');

		if (sourceHex === undefined || targetHex === undefined || sourceHex.trim() === '') {
			return acc;
		}

		const source = fromCodePoints(sourceHex);
		const target = fromCodePoints(targetHex);

		// `toLookalikeKey` decomposes the text (NFD) and drops combining marks before it reads this
		// table, so a character either of those changes never reaches it.
		const reachesTable =
			source.normalize('NFD') === source && !/\p{M}/u.test(source) && source !== target;

		return reachesTable && LATIN_LETTERS_AND_DIGITS.test(target) ? [...acc, [source, target]] : acc;
	}, []);
};

const writeConfusables = (confusables: [string, string][]) => {
	const entries = confusables
		.map(([source, target]) => `\t'${escape(source)}': '${target}'`)
		.join(',\n');

	writeFileSync(
		OUTPUT_FILE,
		`// Generated by scripts/build.confusables.ts from ${CONFUSABLES_URL}. Do not edit by hand.
// Each character that looks like Latin letters or digits, mapped to them.
export const CONFUSABLES: Readonly<Record<string, string>> = {
${entries}
};
`
	);
};

const confusables = await buildConfusables();

writeConfusables(confusables);

console.log(`Wrote ${confusables.length} lookalike characters to ${OUTPUT_FILE}.`);
