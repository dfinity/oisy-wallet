<script lang="ts">
	import { isNullish, nonNullish } from '@dfinity/utils';
	import { getContext, onMount } from 'svelte';
	import BtcConvertForm from '$btc/components/convert/BtcConvertForm.svelte';
	import BtcConvertProgress from '$btc/components/convert/BtcConvertProgress.svelte';
	import BtcConvertReview from '$btc/components/convert/BtcConvertReview.svelte';
	import UtxosFeeLoader from '$btc/components/fee/UtxosFeeLoader.svelte';
	import { loadBtcPendingSentTransactions } from '$btc/services/btc-pending-sent-transactions.services';
	import { sendBtc, validateBtcSend } from '$btc/services/btc-send.services';
	import {
		UTXOS_FEE_CONTEXT_KEY,
		type UtxosFeeContext as UtxosFeeContextType
	} from '$btc/stores/utxos-fee.store';
	import {
		isUnclearBtcBroadcastOutcome,
		mapBtcBroadcastErrorToMessage
	} from '$btc/utils/btc-send.utils';
	import { BTC_EXTENSION_FEATURE_FLAG_ENABLED } from '$env/btc.env';
	import { btcAddressStore } from '$icp/stores/btc.store';
	import ButtonBack from '$lib/components/ui/ButtonBack.svelte';
	import ButtonCancel from '$lib/components/ui/ButtonCancel.svelte';
	import {
		TRACK_COUNT_CONVERT_BTC_TO_CKBTC_ERROR,
		TRACK_COUNT_CONVERT_BTC_TO_CKBTC_SUCCESS
	} from '$lib/constants/analytics.constants';
	import {
		btcAddressMainnet,
		btcAddressRegtest,
		btcAddressTestnet
	} from '$lib/derived/address.derived';
	import { authIdentity } from '$lib/derived/auth.derived';
	import { ProgressStepsConvert } from '$lib/enums/progress-steps';
	import { WizardStepsConvert } from '$lib/enums/wizard-steps';
	import { trackEvent } from '$lib/services/analytics.services';
	import { CONVERT_CONTEXT_KEY, type ConvertContext } from '$lib/stores/convert.store';
	import { i18n } from '$lib/stores/i18n.store';
	import { toastsError } from '$lib/stores/toasts.store';
	import type { OptionAmount } from '$lib/types/send';
	import type { WizardStep } from '$lib/types/wizard';
	import { invalidAmount, isNullishOrEmpty } from '$lib/utils/input.utils';
	import {
		isNetworkIdBTCRegtest,
		isNetworkIdBTCTestnet,
		mapNetworkIdToBitcoinNetwork
	} from '$lib/utils/network.utils';

	interface Props {
		sendAmount: OptionAmount;
		receiveAmount?: number;
		convertProgressStep: string;
		currentStep?: WizardStep;
		formCancelAction?: 'back' | 'close';
		onBack: () => void;
		onClose: () => void;
		onNext: () => void;
	}

	let {
		sendAmount = $bindable(),
		receiveAmount = $bindable(),
		convertProgressStep = $bindable(),
		currentStep,
		formCancelAction = 'close',
		onBack,
		onClose,
		onNext
	}: Props = $props();

	const { store: utxosFeeStore } = getContext<UtxosFeeContextType>(UTXOS_FEE_CONTEXT_KEY);

	const { sourceToken, destinationToken } = getContext<ConvertContext>(CONVERT_CONTEXT_KEY);

	const progress = (step: ProgressStepsConvert) => (convertProgressStep = step);

	let amountError = $state(false);

	let networkId = $derived($sourceToken.network.id);

	let sourceAddress = $derived(
		(isNetworkIdBTCTestnet(networkId)
			? $btcAddressTestnet
			: isNetworkIdBTCRegtest(networkId)
				? $btcAddressRegtest
				: $btcAddressMainnet) ?? ''
	);

	// BTC address generated by the ckBTC minter which needs to be used for BTC -> ckBTC conversion
	// Docs: https://github.com/dfinity/ic/blob/master/rs/bitcoin/ckbtc/minter/README.adoc#bitcoin-to-ckbtc
	let destinationAddress = $derived($btcAddressStore?.[$destinationToken.id]?.data);

	onMount(() => {
		loadBtcPendingSentTransactions({
			identity: $authIdentity,
			networkId,
			address: sourceAddress
		});
	});

	const convert = async () => {
		const network = nonNullish(networkId) ? mapNetworkIdToBitcoinNetwork(networkId) : undefined;

		if (isNullish($authIdentity)) {
			return;
		}

		// The data has been already validated in the previous conversion flow steps.
		if (
			isNullish(network) ||
			isNullishOrEmpty(destinationAddress) ||
			invalidAmount(sendAmount) ||
			isNullish(sendAmount) ||
			isNullish($utxosFeeStore?.utxosFee)
		) {
			toastsError({
				msg: { text: $i18n.convert.error.unexpected_missing_data }
			});
			return;
		}

		onNext();

		if (BTC_EXTENSION_FEATURE_FLAG_ENABLED) {
			// Last-line guard against a race: between fee preview and broadcast
			// another tab may have reserved one of the UTXOs we selected.
			try {
				// No recipient: the fee is priced for the largest output, like a swap's (see the loader below).
				await validateBtcSend({
					utxosFee: $utxosFeeStore.utxosFee,
					source: sourceAddress,
					amount: sendAmount,
					network,
					identity: $authIdentity
				});
			} catch (_: unknown) {
				// Go back so the user can refresh the fee preview and retry.
				back();
				return;
			}
		}

		try {
			await sendBtc({
				destination: destinationAddress,
				amount: sendAmount,
				utxosFee: $utxosFeeStore.utxosFee,
				network,
				source: sourceAddress,
				identity: $authIdentity,
				viaBackend: true,
				onProgress: () => {
					if (convertProgressStep === ProgressStepsConvert.INITIALIZATION) {
						progress(ProgressStepsConvert.CONVERT);
					} else if (convertProgressStep === ProgressStepsConvert.CONVERT) {
						progress(ProgressStepsConvert.UPDATE_UI);
					}
				}
			});

			progress(ProgressStepsConvert.DONE);

			trackEvent({
				name: TRACK_COUNT_CONVERT_BTC_TO_CKBTC_SUCCESS
			});

			setTimeout(() => close(), 750);
		} catch (err: unknown) {
			toastsError({
				msg: {
					text:
						mapBtcBroadcastErrorToMessage({ err, i18n: $i18n }) ?? $i18n.convert.error.unexpected
				},
				err
			});

			trackEvent({
				name: TRACK_COUNT_CONVERT_BTC_TO_CKBTC_ERROR
			});

			// As for a send: the conversion may have gone out, so the form is not offered again.
			if (isUnclearBtcBroadcastOutcome(err)) {
				close();
				return;
			}

			back();
		}
	};

	const close = () => onClose();
	const back = () => onBack();
</script>

<!-- No recipient, although the deposit address is the minter's P2WPKH one: priced for the largest
     output, as the Chain Fusion swap prices the same deposit. Pricing the address would make the
     fee wait for it, and an amount refused for the fee before it arrives would keep that fee, since
     the loader skips while `amountError` is set and Convert only re-checks the amount on input. -->
<UtxosFeeLoader amount={sendAmount} {amountError} {networkId} source={sourceAddress}>
	{#key currentStep?.name}
		{#if currentStep?.name === WizardStepsConvert.CONVERT}
			<BtcConvertForm
				{onNext}
				source={sourceAddress}
				bind:sendAmount
				bind:receiveAmount
				bind:amountError
			>
				{#snippet cancel()}
					{#if formCancelAction === 'back'}
						<ButtonBack onclick={back} />
					{:else}
						<ButtonCancel onclick={close} />
					{/if}
				{/snippet}
			</BtcConvertForm>
		{:else if currentStep?.name === WizardStepsConvert.REVIEW}
			<BtcConvertReview onConvert={convert} {receiveAmount} {sendAmount}>
				{#snippet cancel()}
					<ButtonBack onclick={back} />
				{/snippet}
			</BtcConvertReview>
		{:else if currentStep?.name === WizardStepsConvert.CONVERTING}
			<BtcConvertProgress {convertProgressStep} />
		{/if}
	{/key}
</UtxosFeeLoader>
